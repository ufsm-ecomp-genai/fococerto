IDIOMA_PADRAO = "pt-BR"


def textos(idioma: str | None) -> dict:
    """Dicionário de textos do idioma, com fallback por prefixo ("en-US" -> "en") e para pt-BR."""
    base = TEXTOS[IDIOMA_PADRAO]
    if not idioma:
        return base
    escolhido = TEXTOS.get(idioma)
    if escolhido is None:
        prefixo = idioma.split("-")[0].lower()
        escolhido = next((v for k, v in TEXTOS.items() if k.split("-")[0].lower() == prefixo), base)
    return {**base, **escolhido}
